"""Generated views: ROADMAP.md, BACKLOG.md and the stakeholder status report."""
from __future__ import annotations

import re

from trackerlib import queries as q
from trackerlib.doc import Doc
from trackerlib.milestones import milestone_rows
from trackerlib.model import ACTIVE, CLOSED, ITEM_CLOSED, PLAN_FLOW
from trackerlib.sprints import sprint_summary
from trackerlib.store import Store
from trackerlib.text import id_list, today

Docs = dict[str, Doc]
PLAN_HEADER = ["| Plan | Title | Epic | Sprint | Pts | Status | Tasks |", "|---|---|---|---|---|---|---|"]


def _emit(store: Store, name: str, text: str, write: bool) -> None:
    if write:
        (store.dir / name).write_text(text)
        print(f"Wrote {store.rel(store.dir / name)}")
    else:
        print(text)


# ---------------------------------------------------------------- roadmap
def roadmap(store: Store, write: bool = False) -> None:
    epics, items, sprints = store.epics(), store.items(), store.sprints()
    plans = store.plans(include_branches=True)
    lines = ["# Roadmap", "",
             f"_Generated by `tracker.py roadmap` on {today()} from `main` + `plan/*` branches. Do not edit by hand._", ""]
    lines += ["## Milestones", ""] + milestone_rows(store, epics, items, plans, sprints) + [""]
    if active := q.active_sprint(sprints):
        lines += ["## Current sprint", ""] + sprint_summary(active, plans) + [""]
    lines += _plan_sections(plans, sprints)
    lines += _epic_sections(epics, items, plans, sprints)
    lines += _sprint_history(sprints)
    lines += _done_sections(plans)
    out = re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).rstrip() + "\n"
    _emit(store, "ROADMAP.md", out, write)
    if write:
        _emit(store, "BACKLOG.md", backlog_text(store, epics, items, plans), write)


def _plan_row(p: Doc, plans: Docs, sprints: Docs) -> str:
    t = p.tasks()
    progress = f"{sum(1 for d, _ in t if d)}/{len(t)}" if t else "–"
    src = "" if p.source == "worktree" else f" (live on `{p.source}`)"
    waits = q.unmet_deps(p, plans) if p.get("status") not in CLOSED else []
    wait = f" (waits for {', '.join(waits)})" if waits else ""
    sp = q.sprint_of(p.id, sprints)
    return (f"| {p.id} | {p.get('title')} | {p.get('epic') or '—'} | {sp.id if sp else '—'} | {p.points() or '?'} | "
            f"{p.get('status')}{src}{wait} | {progress} |")


def _plan_sections(plans: Docs, sprints: Docs) -> list[str]:
    by_status: dict[str, list[Doc]] = {}
    for p in plans.values():
        by_status.setdefault(p.get("status") or "draft", []).append(p)
    counts = " · ".join(f"{s}: {len(by_status[s])}" for s in PLAN_FLOW if by_status.get(s))
    lines = [f"**Plans** — {counts or 'none yet'}", ""]
    for heading, statuses in (("Now", ("in-progress", "blocked", "in-review")), ("Next (ready)", ("ready",)),
                              ("Drafts", ("draft",))):
        sel = [p for s in statuses for p in by_status.get(s, [])]
        lines += [f"## {heading}", ""]
        lines += (PLAN_HEADER + [_plan_row(p, plans, sprints) for p in sel]) if sel else ["_None._"]
        lines.append("")
    return lines


def _epic_sections(epics: Docs, items: Docs, plans: Docs, sprints: Docs) -> list[str]:
    lines = ["## Epics", ""]
    if not epics:
        return lines + ["_None._", ""]
    for eid, e in epics.items():
        eps, eitems = q.epic_plans(eid, plans), q.epic_items(eid, items)
        done_pts = sum(i.points() or 0 for i in eitems if q.item_status(i, plans) == "done")
        closed = sum(1 for p in eps if p.get("status") in CLOSED)
        lines += [f"### {eid}: {e.get('title')} — {e.get('status')}"
                  + (f" · {e.get('milestone')}" if e.get("milestone") else "")
                  + f" ({closed}/{len(eps)} plans closed, {done_pts}/{sum(i.points() or 0 for i in eitems)} pts)", ""]
        lines += (PLAN_HEADER + [_plan_row(p, plans, sprints) for p in eps]) if eps else ["_No plans yet._"]
        if unplanned := [i for i in eitems if not i.get("plan")]:
            lines += ["", "Not yet planned:"]
            lines += [f"- {i.id}: {i.get('title')} ({i.points() or '?'} pts, {i.get('status')})" for i in unplanned]
        lines.append("")
    return lines


def _sprint_history(sprints: Docs) -> list[str]:
    closed = sorted((s for s in sprints.values() if s.get("status") == "closed"), key=lambda s: s.id)
    if not closed:
        return []
    lines = ["## Sprint history", "", "| Sprint | Dates | Committed | Velocity | Unplanned | Carried over |",
             "|---|---|---|---|---|---|"]
    lines += [f"| {s.id} | {s.get('start')} → {s.get('end')} | {s.get('committed_points') or '?'} | "
              f"{s.get('velocity') or 0} | {s.get('unplanned_points') or 0} | {s.get('carried_over') or '—'} |"
              for s in closed]
    vel = q.velocity(sprints)
    return lines + ["", f"Rolling velocity (last 3): {vel:.1f} pts" if vel else "", ""]


def _done_sections(plans: Docs) -> list[str]:
    done = sorted((p for p in plans.values() if p.get("status") == "done"),
                  key=lambda p: p.get("completed") or "", reverse=True)
    lines = ["## Done", ""]
    lines += ([f"- {p.get('completed') or '?'} — {p.id}: {p.get('title')}"
               + (f" ({p.get('epic')})" if p.get("epic") else "")
               + (f" — {p.get('pr')}" if p.get("pr") else "") for p in done] or ["_None._"])
    if dropped := [p for p in plans.values() if p.get("status") == "dropped"]:
        lines += ["", "## Dropped", ""] + [f"- {p.id}: {p.get('title')}" for p in dropped]
    return lines


# ---------------------------------------------------------------- backlog
def backlog_text(store: Store, epics: Docs, items: Docs, plans: Docs) -> str:
    morder = q.milestone_order(store.milestones())
    ranked = sorted(items.values(), key=lambda i: q.item_rank(i, epics, morder))
    status = {i.id: q.item_status(i, plans) for i in ranked}
    lines = ["# Backlog", "",
             f"_Generated by `tracker.py roadmap --write` on {today()}. Ranked P0 first, then milestone → priority → epic. "
             "Edit the item files in `.project/items/`, not this file._", ""]
    groups = (("Untriaged", ("new",)), ("Ranked backlog (triaged, not yet planned)", ("triaged",)),
              ("Planned / in progress", ("planned", "in-progress")))
    for title, states in groups:
        sel = [i for i in ranked if status[i.id] in states]
        lines += [f"## {title}", ""] + _backlog_rows(sel, status, epics) + [""]
    closed = [i for i in ranked if status[i.id] in ("done", *ITEM_CLOSED)]
    lines += ["## Closed", "", f"{len(closed)} items done, won't fix or duplicate."]
    return "\n".join(lines).rstrip() + "\n"


def _backlog_rows(sel: list[Doc], status: dict[str, str], epics: Docs) -> list[str]:
    if not sel:
        return ["_None._"]
    head = ["| # | ID | Title | Pri | Sev | Pts | Milestone | Epic | Status |", "|---|---|---|---|---|---|---|---|---|"]
    return head + [f"| {n} | {i.id} | {i.get('title')} | {i.get('priority') or '—'} | {i.get('severity') or ''} | "
                   f"{i.points() or '?'} | {q.item_milestone(i, epics) or '—'} | {i.get('epic') or '—'} | "
                   f"{status[i.id]}" + (f" ({i.get('plan')})" if i.get("plan") else "") + " |"
                   for n, i in enumerate(sel, 1)]


# ---------------------------------------------------------------- status report
def status(store: Store, write: bool) -> None:
    store.require()
    epics, items, sprints = store.epics(), store.items(), store.sprints()
    plans = store.plans(include_branches=True)
    lines = [f"# Status report — {today()}", "", "_Generated by `tracker.py status`._", ""]
    lines += ["## Sprint", ""] + _sprint_status(sprints, plans)
    lines += ["", "## Milestones", ""] + milestone_rows(store, epics, items, plans, sprints)
    lines += ["", "## Blocked", ""] + _blocked(plans)
    lines += ["", "## Open bugs", ""] + _open_bugs(items, plans)
    lines += ["", "## Top risks", ""] + _top_risks(store)
    if untriaged := [i.id for i in items.values() if i.get("status") == "new"]:
        lines += ["", f"**Untriaged items:** {', '.join(untriaged)}"]
    _emit(store, "STATUS.md", "\n".join(lines).rstrip() + "\n", write)


def _sprint_status(sprints: Docs, plans: Docs) -> list[str]:
    active = q.active_sprint(sprints)
    if not active:
        return ["_No active sprint._"]
    lines = sprint_summary(active, plans)
    unplanned = [p for p in plans.values() if p.get("status") in ACTIVE | {"done"}
                 and p.id not in id_list(active.get("plans"))
                 and (active.get("start") or "") <= (p.get("started") or p.get("completed") or "")]
    if unplanned:
        lines += ["", "Unplanned work this sprint: " + ", ".join(f"{p.id} ({p.points() or '?'} pts)" for p in unplanned)]
    return lines


def _blocked(plans: Docs) -> list[str]:
    out = []
    for p in (p for p in plans.values() if p.get("status") == "blocked"):
        logs = [ln for ln in p.section("Progress log").splitlines() if ln.strip().startswith("- ")]
        out.append(f"- {p.id}: {p.get('title')} — {logs[-1].strip()[2:] if logs else 'see plan'}")
    return out or ["_None._"]


def _open_bugs(items: Docs, plans: Docs) -> list[str]:
    bugs = sorted((i for i in items.values() if i.id.startswith("BUG-")
                   and q.item_status(i, plans) not in ("done", *ITEM_CLOSED)),
                  key=lambda i: (i.get("severity") or "S9", i.get("priority") or "P9", i.id))
    if not bugs:
        return ["_None._"]
    return ["| Bug | Sev | Pri | Title | Status |", "|---|---|---|---|---|"] + [
        f"| {b.id} | {b.get('severity') or '—'} | {b.get('priority') or '—'} | {b.get('title')} | "
        f"{q.item_status(b, plans)}" + (f" ({b.get('plan')})" if b.get("plan") else "") + " |" for b in bugs]


def _top_risks(store: Store) -> list[str]:
    risks = sorted(store.open_risks(), key=q.risk_score, reverse=True)[:5]
    if not risks:
        return ["_No open risks recorded._"]
    return ["| Risk | P × I | Owner | Mitigation |", "|---|---|---|---|"] + [
        f"| {r.get('id', '')} {r.get('risk', '')} | {r.get('probability', '?')} × {r.get('impact', '?')} | "
        f"{r.get('owner') or '—'} | {r.get('mitigation') or '—'} |" for r in risks]
