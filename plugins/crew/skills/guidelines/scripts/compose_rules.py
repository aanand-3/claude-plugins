#!/usr/bin/env python3
"""Compose guideline packs into .claude/rules/ for a project.

Reads `packs:` from .crew/config.yaml (or --packs a,b,c), resolves `requires`,
and writes one rules file per pack. `base` (no paths) loads every session; the others
are path-scoped so Claude only loads them when touching matching files.

In a monorepo, `architecture.backend_dir` / `architecture.frontend_dir` in config prefix
the globs of backend-/frontend-scoped packs, so React rules never load for backend files
and Python rules never load for frontend files.

Tooling templates are rendered for `modules:` in config: {{#hub}}…{{/hub}} keeps a
block when the hub is on, {{^hub}}…{{/hub}} when it's off.

Usage: compose_rules.py [--root DIR] [--packs a,b] [--dry-run] [--force] [--prune]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

STACKS = Path(__file__).resolve().parent.parent / "stacks"
TOOLING = Path(__file__).resolve().parent.parent / "tooling"
VENDORED = ("check_structure.py", "format_on_edit.py", "track_plan_draft.py")  # copied to .crew/bin/
VENDORED_FOR = {"design": Path(__file__).resolve().parents[2] / "design" / "scripts" / "check_design.py"}  # pack → helper
TOOLING_FOR = {  # pack → tooling subfolders copied to .crew/templates/tooling/
    "python": ["python"], "node": ["node"], "react": ["react"],
    "base": ["common", "ci"],
}
ARCH_TOOLING = {"importlinter.hexagonal.toml": "arch-hexagonal", "importlinter.layered.toml": "arch-layered",
                "importlinter.cli.toml": "cli-python"}  # copied only for the selected architecture
MARKER = "<!-- generated by crew guidelines from pack '{pack}'. Project-specific additions go in a separate rules file. -->"


def frontmatter(text: str) -> tuple[dict[str, str], str]:
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}, text
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta, text[m.end():]


def parse_list(value: str) -> list[str]:
    return [x.strip().strip("\"'") for x in value.strip().strip("[]").split(",") if x.strip()]


def config_text(root: Path) -> str:
    cfg = root / ".crew" / "config.yaml"
    return cfg.read_text() if cfg.is_file() else ""


def scope_dirs(root: Path) -> dict[str, str]:
    """{'backend': 'backend/', 'frontend': 'frontend/'} from config; '' when single-app."""
    text = config_text(root)
    dirs = {}
    for scope in ("backend", "frontend"):
        m = re.search(rf"^\s*{scope}_dir:\s*\"?([^\s\"#]*)", text, re.M)
        d = (m.group(1) if m else "").strip().strip("./")
        dirs[scope] = f"{d}/" if d and d not in ("none", "null") else ""
    return dirs


def modules_from_config(root: Path) -> dict[str, bool]:
    """`modules:` switches; a missing key keeps the pre-modules default (hub on, graphify off)."""
    flags = {"hub": True, "graphify": False}
    m = re.search(r"^modules:[ \t]*\n((?:[ \t]+.*\n?)*)", config_text(root), re.M)
    for key, value in re.findall(r"^[ \t]+(\w+):[ \t]*(\w+)", m.group(1) if m else "", re.M):
        flags[key] = value.lower() == "true"
    return flags


def render_blocks(text: str, flags: dict[str, bool]) -> str:
    """Keep {{#flag}}…{{/flag}} when flag is on and {{^flag}}…{{/flag}} when off; drop the rest."""
    def keep(m: re.Match[str]) -> str:
        return m.group(3) if flags.get(m.group(2), False) == (m.group(1) == "#") else ""
    text = re.sub(r"^\{\{([#^])(\w+)\}\}\n(.*?)^\{\{/\2\}\}\n", keep, text, flags=re.M | re.S)
    return re.sub(r"\{\{([#^])(\w+)\}\}(.*?)\{\{/\2\}\}", keep, text, flags=re.S)


def packs_from_config(root: Path) -> list[str]:
    text = config_text(root)
    if not text:
        sys.exit(f"{root / '.crew/config.yaml'} not found — run discover first or pass --packs.")
    m = re.search(r"^packs:\s*(\[.*?\])", text, re.M | re.S)
    if not m:
        sys.exit("No `packs: [...]` list in .crew/config.yaml")
    return parse_list(m.group(1))


def resolve(packs: list[str]) -> list[str]:
    available = {p.stem for p in STACKS.glob("*.md")}
    ordered: list[str] = []

    def visit(name: str) -> None:
        if name in ordered:
            return
        if name not in available:
            sys.exit(f"Unknown pack '{name}'. Available: {', '.join(sorted(available))}")
        meta, _ = frontmatter((STACKS / f"{name}.md").read_text())
        for dep in parse_list(meta.get("requires", "")):
            visit(dep)
        ordered.append(name)

    for p in ["base", *packs]:
        visit(p)
    return ordered


def render(name: str, dirs: dict[str, str]) -> str:
    meta, body = frontmatter((STACKS / f"{name}.md").read_text())
    paths = parse_list(meta.get("paths", ""))
    prefix = dirs.get(meta.get("scope", "any"), "")
    if prefix:
        paths = [prefix + p for p in paths]
    head = ""
    if paths:
        head = "---\npaths:\n" + "".join(f'  - "{p}"\n' for p in paths) + "---\n"
    return head + MARKER.format(pack=name) + "\n\n" + body.lstrip()


def copy_if_changed(src: Path, dst: Path, root: Path, executable: bool = False, flags: dict[str, bool] | None = None) -> None:
    data = src.read_bytes()
    if flags is not None and b"{{" in data:
        data = render_blocks(data.decode(), flags).encode()
    if dst.exists() and dst.read_bytes() == data:
        return
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_bytes(data)
    if executable:
        dst.chmod(0o755)
    print(f"WRITE  {dst.relative_to(root)}")


def vendor(root: Path, packs: list[str]) -> None:
    """Copy helper scripts and the relevant tooling reference configs into the project,
    so hooks and P-001 work without the plugin installed."""
    here = Path(__file__).resolve().parent
    flags = modules_from_config(root)
    for name in VENDORED:
        if name == "track_plan_draft.py" and not flags["hub"]:  # plan-draft hook only serves the hub
            continue
        copy_if_changed(here / name, root / ".crew" / "bin" / name, root, executable=True)
    for pack, src in VENDORED_FOR.items():
        if pack in packs:
            copy_if_changed(src, root / ".crew" / "bin" / src.name, root, executable=True)
    folders = sorted({f for p in packs for f in TOOLING_FOR.get(p, [])})
    for folder in folders:
        for src in sorted((TOOLING / folder).rglob("*")):
            if src.is_file() and ARCH_TOOLING.get(src.name, "base") in packs:
                copy_if_changed(src, root / ".crew" / "templates" / "tooling" / src.relative_to(TOOLING), root, flags=flags)
    if (TOOLING / "README.md").is_file():
        copy_if_changed(TOOLING / "README.md", root / ".crew" / "templates" / "tooling" / "README.md", root, flags=flags)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    ap.add_argument("--packs")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--force", action="store_true", help="overwrite rules files that were edited by hand")
    ap.add_argument("--prune", action="store_true", help="delete generated rules files for packs no longer selected")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    packs = resolve(parse_list(args.packs) if args.packs else packs_from_config(root))
    dirs = scope_dirs(root)
    out_dir = root / ".claude" / "rules"
    if not args.dry_run:
        out_dir.mkdir(parents=True, exist_ok=True)
    for name in packs:
        target = out_dir / f"{name}.md"
        content = render(name, dirs)
        if target.exists() and target.read_text() == content:
            print(f"OK     {target.relative_to(root)} (unchanged)")
            continue
        if target.exists():
            generated = MARKER.format(pack=name) in target.read_text()
            if not args.force:
                print(f"SKIP   {target.relative_to(root)} (differs from pack{'' if generated else ', not generated'}; use --force)")
                continue
        print(f"{'WOULD WRITE' if args.dry_run else 'WRITE'}  {target.relative_to(root)}")
        if not args.dry_run:
            target.write_text(content)
    if not args.dry_run and (root / ".crew").is_dir():
        vendor(root, packs)
    # generated files whose pack is no longer selected
    for existing in sorted(out_dir.glob("*.md")) if out_dir.is_dir() else []:
        if existing.stem not in packs and MARKER.format(pack=existing.stem) in existing.read_text():
            if args.prune and not args.dry_run:
                existing.unlink()
                print(f"REMOVE {existing.relative_to(root)}")
            else:
                print(f"STALE  {existing.relative_to(root)} (pack not selected; --prune to remove)")


if __name__ == "__main__":
    main()
