/** Generated views: ROADMAP.md, BACKLOG.md and the stakeholder status report. */
import type { Doc } from "../core/doc.js";
import { ACTIVE, CLOSED, ITEM_CLOSED, PLAN_FLOW } from "../core/model.js";
import * as q from "../core/queries.js";
import type { Docs, Store } from "../core/store.js";
import { byKey, fixed, idList, today } from "../core/text.js";
import { milestoneRows } from "./milestones.js";
import { closedSprints, sprintSummary } from "./sprints.js";

const PLAN_HEADER = ["| Plan | Title | Goal | Sprint | Pts | Status | Tasks |", "|---|---|---|---|---|---|---|"];
const sum = (docs: Doc[]) => docs.reduce((n, d) => n + (d.points() ?? 0), 0);

function emit(store: Store, name: string, text: string, write: boolean): void {
  if (write) {
    store.ws.write(`${store.dir}/${name}`, text);
    store.say(`Wrote ${store.rel(`${store.dir}/${name}`)}`);
  } else {
    store.say(text);
  }
}

// ---------------------------------------------------------------- roadmap
export function roadmap(store: Store, write = false): void {
  const goals = store.goals(), items = store.items(), sprints = store.sprints();
  const plans = store.plans(true);
  const lines = ["# Roadmap", "",
    `_Generated by \`crew.mjs roadmap\` on ${today()} from \`main\` + \`plan/*\` branches. Do not edit by hand._`, ""];
  lines.push("## Milestones", "", ...milestoneRows(store, goals, items, plans, sprints), "");
  const active = q.activeSprint(sprints);
  if (active) lines.push("## Current sprint", "", ...sprintSummary(active, plans), "");
  lines.push(...planSections(plans, sprints), ...goalSections(goals, items, plans, sprints),
    ...sprintHistory(sprints), ...doneSections(plans));
  emit(store, "ROADMAP.md", `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`, write);
  if (write) emit(store, "BACKLOG.md", backlogText(store, goals, items, plans), write);
}

function planRow(p: Doc, plans: Docs, sprints: Docs): string {
  const t = p.tasks();
  const progress = t.length ? `${t.filter(([d]) => d).length}/${t.length}` : "–";
  const src = p.source === "worktree" ? "" : ` (live on \`${p.source}\`)`;
  const waits = CLOSED.has(p.get("status") ?? "") ? [] : q.unmetDeps(p, plans);
  const wait = waits.length ? ` (waits for ${waits.join(", ")})` : "";
  const sp = q.sprintOf(p.id, sprints);
  return `| ${p.id} | ${p.get("title")} | ${p.get("goal") || "—"} | ${sp ? sp.id : "—"} | ${p.points() || "?"} | `
    + `${p.get("status")}${src}${wait} | ${progress} |`;
}

function planSections(plans: Docs, sprints: Docs): string[] {
  const byStatus = new Map<string, Doc[]>();
  for (const p of plans.values()) {
    const st = p.get("status") || "draft";
    byStatus.set(st, [...(byStatus.get(st) ?? []), p]);
  }
  const counts = Object.keys(PLAN_FLOW).filter((s) => byStatus.get(s)?.length)
    .map((s) => `${s}: ${byStatus.get(s)!.length}`).join(" · ");
  const lines = [`**Plans** — ${counts || "none yet"}`, ""];
  const groups: [string, string[]][] = [["Now", ["in-progress", "blocked", "in-review"]], ["Next (ready)", ["ready"]],
    ["Drafts", ["draft"]]];
  for (const [heading, statuses] of groups) {
    const sel = statuses.flatMap((s) => byStatus.get(s) ?? []);
    lines.push(`## ${heading}`, "", ...(sel.length ? [...PLAN_HEADER, ...sel.map((p) => planRow(p, plans, sprints))] : ["_None._"]), "");
  }
  return lines;
}

function goalSections(goals: Docs, items: Docs, plans: Docs, sprints: Docs): string[] {
  const lines = ["## Goals", ""];
  if (!goals.size) return [...lines, "_None._", ""];
  for (const [eid, e] of goals) {
    const eps = q.goalPlans(eid, plans), eitems = q.goalItems(eid, items);
    const donePts = sum(eitems.filter((i) => q.itemStatus(i, plans) === "done"));
    const closed = eps.filter((p) => CLOSED.has(p.get("status") ?? "")).length;
    lines.push(`### ${eid}: ${e.get("title")} — ${e.get("status")}` + (e.get("milestone") ? ` · ${e.get("milestone")}` : "")
      + ` (${closed}/${eps.length} plans closed, ${donePts}/${sum(eitems)} pts)`, "");
    lines.push(...(eps.length ? [...PLAN_HEADER, ...eps.map((p) => planRow(p, plans, sprints))] : ["_No plans yet._"]));
    const unplanned = eitems.filter((i) => !i.get("plan"));
    if (unplanned.length) {
      lines.push("", "Not yet planned:",
        ...unplanned.map((i) => `- ${i.id}: ${i.get("title")} (${i.points() || "?"} pts, ${i.get("status")})`));
    }
    lines.push("");
  }
  return lines;
}

function sprintHistory(sprints: Docs): string[] {
  const closed = closedSprints(sprints);
  if (!closed.length) return [];
  const lines = ["## Sprint history", "", "| Sprint | Dates | Committed | Velocity | Unplanned | Carried over |",
    "|---|---|---|---|---|---|",
    ...closed.map((s) => `| ${s.id} | ${s.get("start")} → ${s.get("end")} | ${s.get("committed_points") || "?"} | `
      + `${s.get("velocity") || 0} | ${s.get("unplanned_points") || 0} | ${s.get("carried_over") || "—"} |`)];
  const vel = q.velocity(sprints);
  return [...lines, "", vel ? `Rolling velocity (last 3): ${fixed(vel, 1)} pts` : "", ""];
}

function doneSections(plans: Docs): string[] {
  const done = [...plans.values()].filter((p) => p.get("status") === "done")
    .sort((a, b) => byKey<Doc>((p) => [p.get("completed") ?? ""])(b, a)); // newest first, stable
  const lines = ["## Done", ""];
  lines.push(...(done.length ? done.map((p) => `- ${p.get("completed") || "?"} — ${p.id}: ${p.get("title")}`
    + (p.get("goal") ? ` (${p.get("goal")})` : "") + (p.get("pr") ? ` — ${p.get("pr")}` : "")) : ["_None._"]));
  const dropped = [...plans.values()].filter((p) => p.get("status") === "dropped");
  if (dropped.length) lines.push("", "## Dropped", "", ...dropped.map((p) => `- ${p.id}: ${p.get("title")}`));
  return lines;
}

// ---------------------------------------------------------------- backlog
export function backlogText(store: Store, goals: Docs, items: Docs, plans: Docs): string {
  const morder = q.milestoneOrder(store.milestones());
  const ranked = [...items.values()].sort(byKey((i) => q.itemRank(i, goals, morder)));
  const status = new Map(ranked.map((i) => [i.id, q.itemStatus(i, plans)]));
  const lines = ["# Backlog", "",
    `_Generated by \`crew.mjs roadmap --write\` on ${today()}. Ranked P0 first, then milestone → priority → goal. `
      + "Edit the item files in `.crew/items/`, not this file._", ""];
  const groups: [string, string[]][] = [["Untriaged", ["new"]], ["Ranked backlog (triaged, not yet planned)", ["triaged"]],
    ["Planned / in progress", ["planned", "in-progress"]]];
  for (const [title, states] of groups) {
    const sel = ranked.filter((i) => states.includes(status.get(i.id)!));
    lines.push(`## ${title}`, "", ...backlogRows(sel, status, goals), "");
  }
  const closed = ranked.filter((i) => ["done", ...ITEM_CLOSED].includes(status.get(i.id)!));
  lines.push("## Closed", "", `${closed.length} items done, won't fix or duplicate.`);
  return `${lines.join("\n").trimEnd()}\n`;
}

function backlogRows(sel: Doc[], status: Map<string, string>, goals: Docs): string[] {
  if (!sel.length) return ["_None._"];
  return ["| # | ID | Title | Pri | Sev | Pts | Milestone | Goal | Status |", "|---|---|---|---|---|---|---|---|---|",
    ...sel.map((i, n) => `| ${n + 1} | ${i.id} | ${i.get("title")} | ${i.get("priority") || "—"} | ${i.get("severity") || ""} | `
      + `${i.points() || "?"} | ${q.itemMilestone(i, goals) || "—"} | ${i.get("goal") || "—"} | `
      + `${status.get(i.id)}` + (i.get("plan") ? ` (${i.get("plan")})` : "") + " |")];
}

// ---------------------------------------------------------------- status report
export function status(store: Store, write: boolean): void {
  store.require();
  const goals = store.goals(), items = store.items(), sprints = store.sprints();
  const plans = store.plans(true);
  const lines = [`# Status report — ${today()}`, "", "_Generated by `crew.mjs status`._", ""];
  lines.push("## Sprint", "", ...sprintStatus(sprints, plans));
  lines.push("", "## Milestones", "", ...milestoneRows(store, goals, items, plans, sprints));
  lines.push("", "## Blocked", "", ...blocked(plans));
  lines.push("", "## Open bugs", "", ...openBugs(items, plans));
  lines.push("", "## Top risks", "", ...topRisks(store));
  const untriaged = [...items.values()].filter((i) => i.get("status") === "new").map((i) => i.id);
  if (untriaged.length) lines.push("", `**Untriaged items:** ${untriaged.join(", ")}`);
  emit(store, "STATUS.md", `${lines.join("\n").trimEnd()}\n`, write);
}

function sprintStatus(sprints: Docs, plans: Docs): string[] {
  const active = q.activeSprint(sprints);
  if (!active) return ["_No active sprint._"];
  const lines = sprintSummary(active, plans);
  const committed = idList(active.get("plans"));
  const unplanned = [...plans.values()].filter((p) => (ACTIVE.has(p.get("status") ?? "") || p.get("status") === "done")
    && !committed.includes(p.id) && (active.get("start") ?? "") <= (p.get("started") || p.get("completed") || ""));
  if (unplanned.length) {
    lines.push("", "Unplanned work this sprint: " + unplanned.map((p) => `${p.id} (${p.points() || "?"} pts)`).join(", "));
  }
  return lines;
}

function blocked(plans: Docs): string[] {
  const out = [...plans.values()].filter((p) => p.get("status") === "blocked").map((p) => {
    const logs = p.section("Progress log").split("\n").filter((l) => l.trim().startsWith("- "));
    return `- ${p.id}: ${p.get("title")} — ${logs.length ? logs[logs.length - 1].trim().slice(2) : "see plan"}`;
  });
  return out.length ? out : ["_None._"];
}

function openBugs(items: Docs, plans: Docs): string[] {
  const bugs = [...items.values()].filter((i) => i.id.startsWith("BUG-") && !["done", ...ITEM_CLOSED].includes(q.itemStatus(i, plans)))
    .sort(byKey((i) => [i.get("severity") || "S9", i.get("priority") || "P9", i.id]));
  if (!bugs.length) return ["_None._"];
  return ["| Bug | Sev | Pri | Title | Status |", "|---|---|---|---|---|",
    ...bugs.map((b) => `| ${b.id} | ${b.get("severity") || "—"} | ${b.get("priority") || "—"} | ${b.get("title")} | `
      + q.itemStatus(b, plans) + (b.get("plan") ? ` (${b.get("plan")})` : "") + " |")];
}

function topRisks(store: Store): string[] {
  const risks = store.openRisks().sort(byKey((r) => [-q.riskScore(r)])).slice(0, 5);
  if (!risks.length) return ["_No open risks recorded._"];
  return ["| Risk | P × I | Owner | Mitigation |", "|---|---|---|---|",
    ...risks.map((r) => `| ${r.id ?? ""} ${r.risk ?? ""} | ${r.probability ?? "?"} × ${r.impact ?? "?"} | `
      + `${r.owner || "—"} | ${r.mitigation || "—"} |`)];
}
