/** `export`: the graph as JSON, or the self-contained HTML view (ui.html with the graph embedded). */
import { join, resolve } from "node:path";
import type { Graph } from "../graph-types.js";
import { SCRIPT_DIR, type Store } from "../core/store.js";
import { fail } from "../core/text.js";
import { buildGraph } from "./graph.js";

/** The marker the UI bundle carries where the data goes; the page reads it back by id. */
export const DATA_SLOT = '<script id="graph" type="application/json">null</script>';
export const UI_FILE = "ui.html"; // next to crew.mjs: dist/ in the plugin, .crew/bin/ when vendored

/** JSON that is safe inside a <script> element. */
export function embed(graph: Graph): string {
  return JSON.stringify(graph).replace(/</g, "\\u003c"); // no "</script>" or "<!--" can end the element early
}

/** The UI bundle as shipped: the page loads its data from the server when the slot is empty. */
export function renderHtmlShell(store: Store): string {
  const shell = store.ws.read(join(SCRIPT_DIR, UI_FILE));
  if (shell === null || !shell.includes(DATA_SLOT)) {
    fail(`The UI bundle (${UI_FILE}) is missing next to crew.mjs. Re-run \`crew.mjs init\` from the plugin.`);
  }
  return shell;
}

export function renderHtml(store: Store, graph: Graph): string {
  return renderHtmlShell(store).replace(DATA_SLOT, () => `<script id="graph" type="application/json">${embed(graph)}</script>`);
}

export function exportGraph(store: Store, format: "json" | "html", out?: string): void {
  const graph = buildGraph(store);
  if (format === "json") {
    const text = `${JSON.stringify(graph, null, 2)}\n`;
    if (!out) return store.say(text.trimEnd());
    store.ws.write(resolve(out), text);
    return store.say(`Wrote ${store.rel(resolve(out))}`);
  }
  const path = out ? resolve(out) : join(store.dir, "view", "index.html");
  if (!out) store.ws.write(join(store.dir, "view", ".gitignore"), "# generated by `crew.mjs export`\n*\n");
  store.ws.write(path, renderHtml(store, graph));
  store.say(`Wrote ${store.rel(path)} — open it in a browser (it works offline; re-run export to refresh)`);
}
