/** Compose guideline packs into .claude/rules/ for a project.
 *
 * Reads `packs:` from .crew/config.yaml (or --packs a,b,c), resolves `requires`,
 * and writes one rules file per pack. `base` (no paths) loads every session; the others
 * are path-scoped so Claude only loads them when touching matching files.
 *
 * In a monorepo, `architecture.backend_dir` / `architecture.frontend_dir` in config prefix
 * the globs of backend-/frontend-scoped packs, so React rules never load for backend files
 * and Python rules never load for frontend files.
 *
 * Usage: compose_rules.mjs [--root DIR] [--packs a,b] [--dry-run] [--force] [--prune]
 */
import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve as resolvePath } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const HERE = dirname(fileURLToPath(import.meta.url));
const STACKS = join(HERE, "..", "stacks");
const TOOLING = join(HERE, "..", "tooling");
const VENDORED = ["check_structure.mjs", "format_on_edit.mjs", "track_plan_draft.mjs"]; // copied to .crew/bin/
const VENDORED_FOR: Record<string, string> = { design: join(HERE, "..", "..", "design", "scripts", "check_design.mjs") }; // pack → helper
const TOOLING_FOR: Record<string, string[]> = { // pack → tooling subfolders copied to .crew/templates/tooling/
  python: ["python"], node: ["node"], react: ["react"],
  base: ["common", "ci"],
};
const ARCH_TOOLING: Record<string, string> = { "importlinter.hexagonal.toml": "arch-hexagonal", "importlinter.layered.toml": "arch-layered",
  "importlinter.cli.toml": "cli-python" }; // copied only for the selected architecture
const marker = (pack: string) => `<!-- generated by crew guidelines from pack '${pack}'. Project-specific additions go in a separate rules file. -->`;

const isFile = (p: string) => existsSync(p) && statSync(p).isFile();
const isDir = (p: string) => existsSync(p) && statSync(p).isDirectory();
/** Python's str.strip(chars). */
const stripChars = (s: string, chars: string) => {
  let a = 0, b = s.length;
  while (a < b && chars.includes(s[a])) a++;
  while (b > a && chars.includes(s[b - 1])) b--;
  return s.slice(a, b);
};
const rel = (p: string, root: string) => relative(root, p);

function fail(message: string): never {
  console.error(message);
  process.exit(1);
}

function frontmatter(text: string): [Record<string, string>, string] {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!m) return [{}, text];
  const meta: Record<string, string> = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i >= 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return [meta, text.slice(m[0].length)];
}

function parseList(value: string): string[] {
  return stripChars(value.trim(), "[]").split(",").filter((x) => x.trim()).map((x) => stripChars(x.trim(), "\"'"));
}

function configText(root: string): string {
  const cfg = join(root, ".crew", "config.yaml");
  return isFile(cfg) ? readFileSync(cfg, "utf8") : "";
}

/** {backend: 'backend/', frontend: 'frontend/'} from config; '' when single-app. */
function scopeDirs(root: string): Record<string, string> {
  const text = configText(root);
  const dirs: Record<string, string> = {};
  for (const scope of ["backend", "frontend"]) {
    const m = new RegExp(`^\\s*${scope}_dir:\\s*"?([^\\s"#]*)`, "m").exec(text);
    const d = stripChars((m ? m[1] : "").trim(), "./");
    dirs[scope] = d && !["none", "null"].includes(d) ? `${d}/` : "";
  }
  return dirs;
}

function packsFromConfig(root: string): string[] {
  const text = configText(root);
  if (!text) fail(`${join(root, ".crew/config.yaml")} not found — run discover first or pass --packs.`);
  const m = /^packs:\s*(\[[\s\S]*?\])/m.exec(text);
  if (!m) fail("No `packs: [...]` list in .crew/config.yaml");
  return parseList(m[1]);
}

function resolve(packs: string[]): string[] {
  const available = new Set(readdirSync(STACKS).filter((f) => f.endsWith(".md")).map((f) => f.slice(0, -3)));
  const ordered: string[] = [];
  const visit = (name: string): void => {
    if (ordered.includes(name)) return;
    if (!available.has(name)) fail(`Unknown pack '${name}'. Available: ${[...available].sort().join(", ")}`);
    const [meta] = frontmatter(readFileSync(join(STACKS, `${name}.md`), "utf8"));
    for (const dep of parseList(meta.requires ?? "")) visit(dep);
    ordered.push(name);
  };
  for (const p of ["base", ...packs]) visit(p);
  return ordered;
}

function render(name: string, dirs: Record<string, string>): string {
  const [meta, body] = frontmatter(readFileSync(join(STACKS, `${name}.md`), "utf8"));
  let paths = parseList(meta.paths ?? "");
  const prefix = dirs[meta.scope ?? "any"] ?? "";
  if (prefix) paths = paths.map((p) => prefix + p);
  const head = paths.length ? "---\npaths:\n" + paths.map((p) => `  - "${p}"\n`).join("") + "---\n" : "";
  return head + marker(name) + "\n\n" + body.trimStart();
}

function copyIfChanged(src: string, dst: string, root: string, executable = false): void {
  const data = readFileSync(src);
  if (existsSync(dst) && readFileSync(dst).equals(data)) return;
  mkdirSync(dirname(dst), { recursive: true });
  writeFileSync(dst, data);
  if (executable) chmodSync(dst, 0o755);
  console.log(`WRITE  ${rel(dst, root)}`);
}

/** Every file under dir, ordered like Python's sorted(Path.rglob("*")) (by path components). */
function filesUnder(dir: string): string[] {
  const all = readdirSync(dir, { recursive: true, encoding: "utf8" }).filter((f) => isFile(join(dir, f)));
  return all.sort((a, b) => {
    const pa = a.split("/"), pb = b.split("/");
    for (let i = 0; i < Math.min(pa.length, pb.length); i++) if (pa[i] !== pb[i]) return pa[i] < pb[i] ? -1 : 1;
    return pa.length - pb.length;
  });
}

/** Copy helper scripts and the relevant tooling reference configs into the project,
 * so hooks and P-001 work without the plugin installed. */
function vendor(root: string, packs: string[]): void {
  for (const name of VENDORED) copyIfChanged(join(HERE, name), join(root, ".crew", "bin", name), root, true);
  for (const [pack, src] of Object.entries(VENDORED_FOR)) {
    if (packs.includes(pack)) copyIfChanged(src, join(root, ".crew", "bin", src.split("/").at(-1)!), root, true);
  }
  const folders = [...new Set(packs.flatMap((p) => TOOLING_FOR[p] ?? []))].sort();
  for (const folder of folders) {
    for (const f of filesUnder(join(TOOLING, folder))) {
      const name = f.split("/").at(-1)!;
      if (packs.includes(ARCH_TOOLING[name] ?? "base")) {
        copyIfChanged(join(TOOLING, folder, f), join(root, ".crew", "templates", "tooling", folder, f), root);
      }
    }
  }
  if (isFile(join(TOOLING, "README.md"))) {
    copyIfChanged(join(TOOLING, "README.md"), join(root, ".crew", "templates", "tooling", "README.md"), root);
  }
}

function main(): void {
  const { values: args } = parseArgs({ options: {
    root: { type: "string", default: "." }, packs: { type: "string" },
    "dry-run": { type: "boolean", default: false }, force: { type: "boolean", default: false }, prune: { type: "boolean", default: false },
  } });
  const root = resolvePath(args.root!);
  const dry = args["dry-run"]!;
  const packs = resolve(args.packs ? parseList(args.packs) : packsFromConfig(root));
  const dirs = scopeDirs(root);
  const outDir = join(root, ".claude", "rules");
  if (!dry) mkdirSync(outDir, { recursive: true });
  for (const name of packs) {
    const target = join(outDir, `${name}.md`);
    const content = render(name, dirs);
    if (existsSync(target) && readFileSync(target, "utf8") === content) {
      console.log(`OK     ${rel(target, root)} (unchanged)`);
      continue;
    }
    if (existsSync(target)) {
      const generated = readFileSync(target, "utf8").includes(marker(name));
      if (!args.force) {
        console.log(`SKIP   ${rel(target, root)} (differs from pack${generated ? "" : ", not generated"}; use --force)`);
        continue;
      }
    }
    console.log(`${dry ? "WOULD WRITE" : "WRITE"}  ${rel(target, root)}`);
    if (!dry) writeFileSync(target, content);
  }
  if (!dry && isDir(join(root, ".crew"))) vendor(root, packs);
  // generated files whose pack is no longer selected
  for (const f of isDir(outDir) ? readdirSync(outDir).filter((n) => n.endsWith(".md")).sort() : []) {
    const existing = join(outDir, f), stem = f.slice(0, -3);
    if (!packs.includes(stem) && readFileSync(existing, "utf8").includes(marker(stem))) {
      if (args.prune && !dry) {
        unlinkSync(existing);
        console.log(`REMOVE ${rel(existing, root)}`);
      } else {
        console.log(`STALE  ${rel(existing, root)} (pack not selected; --prune to remove)`);
      }
    }
  }
}

main();
