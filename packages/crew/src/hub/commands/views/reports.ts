/** `status`: one report of where the work stands, for agents and the executive (STATUS.md with --write). */
import type { Doc } from "../../core/work/doc.js";
import { paused, staleClaims } from "../team/liveness.js";
import type { LedgerEvent } from "../../core/memory/ledger.js";
import { ITEM_CLOSED } from "../../core/work/model.js";
import * as q from "../../core/work/queries.js";
import { openQuestions } from "../team/questions.js";
import type { Docs, Store } from "../../core/store.js";
import { byKey, firstParagraph, stripComments, today } from "../../core/text.js";

const TOP = 5;
const PLAN_HEADER = ["| Plan | Title | Goal | Status | Tasks | Owner |", "|---|---|---|---|---|---|"];

export function status(store: Store, write: boolean): void {
  store.require();
  const goals = store.goals(), items = store.items(), plans = store.plans(true), focus = store.focus();
  const lines = [`# Status — ${today()}`, "", "_Generated by `crew.mjs status`. Do not edit by hand._", ""];
  const halt = paused(store.ledger.events());
  if (halt) lines.push(`**Team paused** by ${halt.actor} since ${halt.ts.slice(0, 16).replace("T", " ")}: ${halt.reason ?? "no reason given"}`, "");
  lines.push("## Idea and focus", "", ...ideaLines(store, goals, plans, items, focus), "");
  const stale = staleClaims(store);
  if (stale.length) lines.push("## Stale claims", "", ...stale.map((s) => `- ${s.ref} — ${s.actor} (${s.run}), no activity for ${s.hours}h`), "");
  const claims = store.ledger.claims();
  lines.push("## Now", "", ...planTable(byStatus(plans, ["in-progress", "in-review"]), plans, items, claims), "");
  lines.push("## Blocked", "", ...blocked(plans), "");
  const asks = openQuestions(store.ledger.events());
  if (asks.length) {
    lines.push("## Open questions", "", ...asks.sort((a, b) => Number(b.escalation) - Number(a.escalation)).map((x) =>
      `- ${x.escalation ? "**escalation** " : ""}${x.id} ${x.by} → ${x.to}${x.ref ? ` about ${x.ref}` : ""}: ${x.text}`), "");
  }
  lines.push("## Ready to start", "", ...planTable(byStatus(plans, ["ready"]), plans, items, claims), "");
  lines.push("## Top of the backlog", "", ...backlogTop(q.ranked(items, goals, focus), plans), "");
  lines.push("## Open bugs", "", ...openBugs(items, plans), "");
  lines.push("## Recently done", "", ...recentlyDone(plans));
  const learned = store.knowledge(false).filter((e) => !e.supersededBy)
    .sort(byKey((e) => [e.doc.get("created") ?? "", e.id])).reverse().slice(0, TOP);
  if (learned.length) {
    lines.push("", "## Recent knowledge", "", ...learned.map((e) => `- ${e.id} [${e.type}] ${e.title}`
      + (e.scope.length ? ` (${e.scope.join(", ")})` : "")));
  }
  const spend = store.ledger.spend();
  if (spend.cost || spend.tokensIn || spend.tokensOut) {
    lines.push("", "## Spend", "", `$${spend.cost.toFixed(2)} · ${spend.tokensIn + spend.tokensOut} tokens — `
      + Object.entries(spend.byActor).sort(([, a], [, b]) => b - a).map(([who, c]) => `${who} $${c.toFixed(2)}`).join(", "));
  }
  const untriaged = [...items.values()].filter((i) => i.get("status") === "new").map((i) => i.id);
  if (untriaged.length) lines.push("", `**Untriaged items:** ${untriaged.join(", ")}`);
  const text = `${lines.join("\n").trimEnd()}\n`;
  if (!write) return store.say(text.trimEnd());
  store.ws.write(`${store.dir}/STATUS.md`, text);
  store.say(`Wrote ${store.rel(`${store.dir}/STATUS.md`)}`);
}

function ideaLines(store: Store, goals: Docs, plans: Docs, items: Docs, focus: string): string[] {
  const idea = store.idea();
  if (!idea) return ["_No idea written yet._"];
  const criteria = idea.checklist("Success criteria");
  const out = [`**${idea.get("title")}** — ${idea.get("status")}`
    + (criteria.length ? ` · success criteria ${criteria.filter(([d]) => d).length}/${criteria.length} met` : "")];
  const g = goals.get(focus);
  if (!g) return [...out, "", "_No focus goal._"];
  const gp = q.goalPlans(focus, plans, items);
  const closed = gp.filter((p) => ["done", "dropped"].includes(p.get("status") ?? "")).length;
  const outcome = firstParagraph(g.section("Outcome"));
  return [...out, "", `Focus **${focus}: ${g.get("title")}** — ${g.get("status")}, ${closed}/${gp.length} plans closed`,
    ...(outcome ? [`> ${outcome}`] : [])];
}

function byStatus(plans: Docs, statuses: string[]): Doc[] {
  return [...plans.values()].filter((p) => statuses.includes(p.get("status") ?? "")).sort(byKey((p) => [p.id]));
}

function planTable(sel: Doc[], plans: Docs, items: Docs, claims: Map<string, LedgerEvent>): string[] {
  if (!sel.length) return ["_None._"];
  return [...PLAN_HEADER, ...sel.map((p) => {
    const t = p.tasks();
    const waits = q.unmetDeps(p, plans);
    const src = p.source === "worktree" ? "" : ` (live on \`${p.source}\`)`;
    return `| ${p.id} | ${p.get("title")} | ${q.planGoal(p, items) || "—"} | ${p.get("status")}${src}`
      + (waits.length ? ` (waits for ${waits.join(", ")})` : "") + ` | ${t.length ? `${t.filter(([d]) => d).length}/${t.length}` : "–"} | `
      + `${claims.get(p.id)?.actor ?? "—"} |`;
  })];
}

function blocked(plans: Docs): string[] {
  const out = byStatus(plans, ["blocked"]).map((p) => {
    const logs = p.section("Progress log").split("\n").filter((l) => l.trim().startsWith("- "));
    return `- ${p.id}: ${p.get("title")} — ${logs.length ? logs[logs.length - 1].trim().slice(2) : "see plan"}`;
  });
  return out.length ? out : ["_None._"];
}

function backlogTop(ranked: Doc[], plans: Docs): string[] {
  const top = ranked.filter((i) => q.itemStatus(i, plans) === "triaged").slice(0, TOP);
  if (!top.length) return ["_Nothing triaged and unplanned._"];
  return ["| # | Item | Title | Pri | Goal |", "|---|---|---|---|---|",
    ...top.map((i, n) => `| ${n + 1} | ${i.id} | ${i.get("title")} | ${i.get("priority") || "—"} | ${i.get("goal") || "—"} |`)];
}

function openBugs(items: Docs, plans: Docs): string[] {
  const bugs = [...items.values()].filter((i) => i.id.startsWith("BUG-") && !["done", ...ITEM_CLOSED].includes(q.itemStatus(i, plans)))
    .sort(byKey((i) => [i.get("severity") || "S9", i.get("priority") || "P9", i.id]));
  if (!bugs.length) return ["_None._"];
  return ["| Bug | Sev | Pri | Title | Status |", "|---|---|---|---|---|",
    ...bugs.map((b) => `| ${b.id} | ${b.get("severity") || "—"} | ${b.get("priority") || "—"} | ${b.get("title")} | `
      + q.itemStatus(b, plans) + (b.get("plan") ? ` (${b.get("plan")})` : "") + " |")];
}

function recentlyDone(plans: Docs): string[] {
  const done = byStatus(plans, ["done"]).sort((a, b) => byKey<Doc>((p) => [p.get("completed") ?? "", p.id])(b, a)).slice(0, TOP);
  return done.length ? done.map((p) => `- ${p.get("completed") || "?"} — ${p.id}: ${p.get("title")}` + (p.get("pr") ? ` — ${p.get("pr")}` : ""))
    : ["_None._"];
}
